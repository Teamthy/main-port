// Generates src/components/Icon.tsx from Material Symbols (Apache 2.0), the
// Google icon set. Only the icons actually used on the site are bundled, as
// inline paths, so there is no icon font to download, no flash of text instead
// of a glyph, and every icon inherits currentColor.
//
// Re-run with: npm run icons:build

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const sourceDir = path.join(root, "node_modules/@material-symbols/svg-400/outlined");
const outFile = path.join(root, "src/components/Icon.tsx");

const ICONS = [
  "account_tree",
  "arrow_back",
  "arrow_forward",
  "arrow_outward",
  "article",
  "call",
  "check",
  "close",
  "code",
  "deployed_code",
  "description",
  "download",
  "keyboard_arrow_down",
  "fact_check",
  "fingerprint",
  "hub",
  "key",
  "language",
  "location_on",
  "lock",
  "mail",
  "menu",
  "north_east",
  "open_in_new",
  "payments",
  "policy",
  "query_stats",
  "radar",
  "schedule",
  "school",
  "science",
  "search_off",
  "shield",
  "star",
  "terminal",
  "verified",
  "visibility",
  "work",
];

const missing = ICONS.filter((name) => !fs.existsSync(path.join(sourceDir, `${name}.svg`)));
if (missing.length) {
  console.error(`Unknown Material Symbols: ${missing.join(", ")}`);
  process.exit(1);
}

const entries = ICONS.map((name) => {
  const svg = fs.readFileSync(path.join(sourceDir, `${name}.svg`), "utf8");
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/\s+/g, " ")
    .trim();
  return `  ${name}: '${inner.replace(/'/g, "\\'")}',`;
}).join("\n");

const file = `// Generated by scripts/generate-icons.mjs. Do not edit by hand.
// Icon glyphs: Material Symbols by Google, Apache License 2.0.
// https://fonts.google.com/icons

export const ICON_NAMES = [
${ICONS.map((name) => `  "${name}",`).join("\n")}
] as const;

export type IconName = (typeof ICON_NAMES)[number];

const PATHS: Record<IconName, string> = {
${entries}
};

export default function Icon({
  name,
  size = 20,
  className = "",
  strokeWidth = 0,
}: {
  name: IconName;
  size?: number | string;
  className?: string;
  strokeWidth?: number;
}) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 -960 960 960"
      width={size}
      height={size}
      fill="currentColor"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      className={\`inline-block shrink-0 \${className}\`}
      aria-hidden="true"
      focusable="false"
      dangerouslySetInnerHTML={{ __html: PATHS[name] }}
    />
  );
}
`;

fs.writeFileSync(outFile, file);
console.log(`Icon.tsx written with ${ICONS.length} Material Symbols`);
